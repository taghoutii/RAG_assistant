"""Phase 4 retrieval table on dev: BM25, dense, hybrid (RRF), hybrid + reranker.

All four setups use the same chunk set (`retrieval` in configs/default.yaml) and the same
first-stage runs, so their per-question scores are paired:
    bm25            BM25 top-n
    dense           dense top-n
    hybrid          RRF of BM25 top-`fusion_depth` and dense top-`fusion_depth`, top-n
    hybrid+rerank   the top `rerank_depth` fused chunks reranked by the cross-encoder, top-n
n = `retrieval_eval.top_n`. Quality is scored on the answerable dev questions (Recall@k, MRR,
nDCG@k with 95% bootstrap intervals, plus paired differences against hybrid). Stage latency is
measured on every dev question after a warm-up, and reported as p50 per stage and per setup.
Questions in `diagnostic_questions` are reported for diagnosis only.

Each setup writes its config + metrics to reports/results/phase4/, and the table is generated
from those files into reports/phase4_retrieval.md.

Usage (PowerShell, from the repo root, on an idle machine; set `retrieval.rerank_depth` first):
    python -m ragpapers.evaluation.run_phase4
"""

import statistics
from datetime import UTC, datetime

from ragpapers.config import REPO_ROOT, load_config
from ragpapers.evaluation.hardware import hardware_info, hardware_line
from ragpapers.evaluation.metrics import credit_quotes
from ragpapers.evaluation.questions import evidence_groups, load_questions
from ragpapers.evaluation.run_retrieval import (
    aggregate,
    fmt,
    paired_difference,
    score_question,
    write_result,
)
from ragpapers.evaluation.split import load_split
from ragpapers.retrieval.pipeline import first_stage, load_indexes, rerank_top
from ragpapers.retrieval.rerank import Reranker

PHASE = "phase4"
SETUPS = ("bm25", "dense", "hybrid", "hybrid+rerank")
STAGES = {  # the stages each setup runs, for its end-to-end latency
    "bm25": ("bm25",),
    "dense": ("dense",),
    "hybrid": ("bm25", "dense", "fusion"),
    "hybrid+rerank": ("bm25", "dense", "fusion", "rerank"),
}
METRICS = ("recall@3", "recall@5", "recall@10", "mrr", "ndcg@10")


def evidence_ranks(
    ranking_texts: list[str], quote_groups: list[list[str]], threshold: float
) -> list:
    """For each evidence group, the 1-based rank of the first chunk containing it (or None)."""
    ranks: list = [None] * len(quote_groups)
    for rank, found in enumerate(credit_quotes(ranking_texts, quote_groups, threshold), start=1):
        for i in found:
            ranks[i] = rank
    return ranks


def make_report(results: dict, latency: dict, diagnostics: list[dict], meta: dict) -> str:
    n_samples, seed = meta["bootstrap_samples"], meta["seed"]
    lines = [
        "# Phase 4: retrieval on dev",
        "",
        "Generated by `python -m ragpapers.evaluation.run_phase4` from reports/results/phase4/. "
        f"Chunks: {meta['chunk_config']} ({meta['n_chunks']} chunks). Hybrid: RRF "
        f"(k={meta['rrf_k']}) of BM25 top-{meta['fusion_depth']} and dense "
        f"top-{meta['fusion_depth']}. Reranker: `{meta['reranker']}` over the top "
        f"{meta['rerank_depth']} fused chunks. Every setup returns its top {meta['top_n']}.",
        "",
        f"Quality: {meta['n_answerable']} answerable dev questions (unanswerable ones have no "
        "evidence). Brackets: 95% bootstrap interval over questions.",
        "",
        "| Setup | Recall@3 | Recall@5 | Recall@10 | MRR | nDCG@10 |",
        "|---|---|---|---|---|---|",
    ]
    for name in SETUPS:
        m = results[name]["metrics"]
        lines.append(f"| {name} | " + " | ".join(fmt(m[k], True) for k in METRICS) + " |")

    lines += [
        "",
        "## Paired differences against hybrid (setup - hybrid)",
        "",
        "| Setup | Recall@3 | Recall@5 | Recall@10 | MRR | nDCG@10 |",
        "|---|---|---|---|---|---|",
    ]
    for name in ("bm25", "dense", "hybrid+rerank"):
        cells = []
        for metric in METRICS:
            diff, low, high = paired_difference(
                results[name], results["hybrid"], metric, 2 * n_samples, seed
            )
            mark = " *" if low > 0 or high < 0 else ""
            cells.append(f"{diff:+.3f} [{low:+.2f}, {high:+.2f}]{mark}")
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    lines += ["", "Paired bootstrap over the same questions; * = the interval excludes 0."]

    lines += [
        "",
        f"## Latency p50 (ms), all {meta['n_latency_questions']} dev questions",
        "",
        f"Hardware: {hardware_line(meta['hardware'])}.",
        "",
        "| Setup | BM25 | Dense (embed + search) | Fusion | Rerank | Total |",
        "|---|---|---|---|---|---|",
    ]
    for name in SETUPS:
        cells = [
            f"{latency['stages'][s]:.1f}" if s in STAGES[name] else "-"
            for s in ("bm25", "dense", "fusion", "rerank")
        ]
        lines.append(f"| {name} | " + " | ".join(cells) + f" | {latency['total'][name]:.0f} |")
    lines += [
        "",
        "Stage columns are per-stage medians; Total is the median of each question's summed "
        "stages, so it is not the sum of the column medians. BM25 and dense run at depth "
        f"{meta['fusion_depth']} in every setup (scoring every chunk costs the same at any depth).",
    ]

    lines += [
        "",
        "## Diagnostics (not used to choose any setting)",
        "",
        "Rank of the first chunk containing each evidence quote; '-' = not found at that depth "
        f"(BM25 and dense: top {meta['fusion_depth']}; hybrid: the full fused list; "
        f"reranked: top {meta['rerank_depth']}).",
        "",
        "| Question | Quote | BM25 | Dense | Hybrid | Reranked |",
        "|---|---|---|---|---|---|",
    ]
    for d in diagnostics:
        for i, quote in enumerate(d["quotes"]):
            cells = [
                str(d["ranks"][s][i]) if d["ranks"][s][i] else "-"
                for s in ("bm25", "dense", "hybrid", "reranked")
            ]
            short = quote if len(quote) <= 60 else quote[:57] + "..."
            lines.append(f"| {d['id']} | {short} | " + " | ".join(cells) + " |")
    lines += ["", f"Bootstrap: {n_samples} resamples of questions, seed {seed}."]
    return "\n".join(lines) + "\n"


def main() -> None:
    config = load_config()
    seed = config["seed"]
    eval_cfg, ret = config["retrieval_eval"], config["retrieval"]
    rerank_depth = ret["rerank_depth"]
    if rerank_depth is None:
        raise SystemExit("Set retrieval.rerank_depth first (python -m ...candidate_depth).")
    threshold, n_samples, top_n = (
        eval_cfg["quote_match_threshold"],
        eval_cfg["bootstrap_samples"],
        eval_cfg["top_n"],
    )

    split_ids = load_split(REPO_ROOT / config["paths"]["eval_splits"], eval_cfg["split"])
    dev = [
        q
        for q in load_questions(REPO_ROOT / config["paths"]["eval_questions"])
        if q["id"] in split_ids
    ]
    n_answerable = sum(1 for q in dev if q["evidence"])
    print(f"{len(dev)} {eval_cfg['split']} questions, {n_answerable} answerable")

    indexes = load_indexes(config)
    by_id = indexes["by_id"]
    reranker = Reranker(config["reranker"]["model"], config["reranker"]["batch_size"])

    # Warm-up: loads both models and the first Qdrant query outside the timings.
    warm, _ = first_stage(dev[0]["question"], indexes, ret["fusion_depth"], ret["rrf_k"])
    rerank_top(dev[0]["question"], warm["hybrid"], rerank_depth, by_id, reranker)
    hardware = hardware_info()

    per_question = {s: [] for s in SETUPS}
    stage_ms = {s: [] for s in ("bm25", "dense", "fusion", "rerank")}
    total_ms = {s: [] for s in SETUPS}
    diagnostics = []
    for q in dev:
        rankings, ms = first_stage(q["question"], indexes, ret["fusion_depth"], ret["rrf_k"])
        reranked, ms["rerank"] = rerank_top(
            q["question"], rankings["hybrid"], rerank_depth, by_id, reranker
        )
        for stage, value in ms.items():
            stage_ms[stage].append(value)
        for name in SETUPS:
            total_ms[name].append(sum(ms[s] for s in STAGES[name]))
        print(f"  {q['id']}: " + "  ".join(f"{s} {v:.0f} ms" for s, v in ms.items()))

        if not q["evidence"]:
            continue
        quotes = evidence_groups(q)
        tops = {
            "bm25": rankings["bm25"],
            "dense": rankings["dense"],
            "hybrid": rankings["hybrid"],
            "hybrid+rerank": reranked,
        }
        for name, ids in tops.items():
            top = [by_id[i] for i in ids[:top_n]]
            scored = score_question(top, quotes, eval_cfg["ks"], threshold)
            per_question[name].append(
                {"id": q["id"], "type": q["type"], "retrieved": ids[:top_n], **scored}
            )
        if q["id"] in config["diagnostic_questions"]:
            lists = {**rankings, "reranked": reranked}
            ranks = {
                s: evidence_ranks([by_id[i]["text"] for i in lists[s]], quotes, threshold)
                for s in ("bm25", "dense", "hybrid", "reranked")
            }
            diagnostics.append({"id": q["id"], "quotes": [g[0] for g in quotes], "ranks": ranks})
    indexes["client"].close()

    latency = {
        "stages": {s: statistics.median(v) for s, v in stage_ms.items()},
        "total": {s: statistics.median(v) for s, v in total_ms.items()},
    }
    created = datetime.now(UTC).isoformat(timespec="seconds")
    results_dir = REPO_ROOT / config["paths"]["results_dir"]
    results = {}
    for name in SETUPS:
        setup = {
            "retriever": name,
            "chunk_config": indexes["name"],
            "n_chunks_searched": len(indexes["chunks"]),
            "include_appendix": True,
            "embedding_model": config["embedding"]["model"],
            "bm25": config["bm25"],
            "fusion_depth": ret["fusion_depth"] if name.startswith("hybrid") else None,
            "rrf_k": ret["rrf_k"] if name.startswith("hybrid") else None,
            "reranker": config["reranker"] if name == "hybrid+rerank" else None,
            "rerank_depth": rerank_depth if name == "hybrid+rerank" else None,
            "top_n": top_n,
            "quote_match_threshold": threshold,
        }
        results[name] = {
            "name": name.replace("+", "_"),
            "phase": PHASE,
            "created_at": created,
            "split": eval_cfg["split"],
            "n_questions": n_answerable,
            "setup": setup,
            "metrics": aggregate(per_question[name], n_samples, seed),
            "latency_ms": {
                "p50": latency["total"][name],
                "mean": statistics.fmean(total_ms[name]),
                "max": max(total_ms[name]),
                "stages_p50": {s: latency["stages"][s] for s in STAGES[name]},
                "n_questions": len(dev),
            },
            "hardware": hardware,
            "per_question": per_question[name],
        }
        write_result(results[name], results_dir)

    meta = {
        "bootstrap_samples": n_samples,
        "seed": seed,
        "chunk_config": indexes["name"],
        "n_chunks": len(indexes["chunks"]),
        "rrf_k": ret["rrf_k"],
        "fusion_depth": ret["fusion_depth"],
        "reranker": config["reranker"]["model"],
        "rerank_depth": rerank_depth,
        "top_n": top_n,
        "n_answerable": n_answerable,
        "n_latency_questions": len(dev),
        "hardware": hardware,
    }
    report = REPO_ROOT / "reports" / "phase4_retrieval.md"
    report.write_text(
        make_report(results, latency, diagnostics, meta), encoding="utf-8", newline="\n"
    )
    print(f"\nWrote reports/results/{PHASE}/*.json and {report}")


if __name__ == "__main__":
    main()
